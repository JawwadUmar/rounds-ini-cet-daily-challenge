test('curriculum and readers omit rotation, origin and count labels; contradictory keys are read-only',async({page})=>{
  await page.goto('/');await page.locator('.library-link').click();
  const forbidden=/days? before|repeats? after|questions? (?:repeat|per subject)|provenance|original practice|AI-authored|MEDINK|extracted from|\d[\d,]* (?:total |practice )?questions\b/i;
  await expect(page.locator('main')).not.toContainText(forbidden);
  await page.getByRole('button',{name:'Browse 2022 paper'}).click();
  await page.getByLabel('Search questions or topics').fill('genetic re-assortment comparable');
  await page.locator('#entry-pyq-2022-67').click();
  await expect(page.getByRole('radio').first()).toBeDisabled();
  await page.getByRole('button',{name:'Read solution'}).click();
  await expect(page.locator('.printed-key')).toContainText('(A)');
  await expect(page.locator('.solution-prose')).toContainText('segmented RNA');
  await expect(page.locator('.quiz-body')).not.toContainText(forbidden);
});

test('PYQ library metrics follow filters, clear only the confirmed scope, and number filtered questions',async({page})=>{
  await page.goto('/');await page.locator('.library-link').click();
  const yearQuestions=bank.filter(q=>q.examYear===2020);
  const anatomyQuestions=yearQuestions.filter(q=>q.subject==='Anatomy');
  await page.getByRole('button',{name:'Browse 2020 paper'}).click();
  await expect(page.locator('.pyq-filter-metrics')).toContainText(`0/${yearQuestions.length}`);
  await expect(page.locator('.question-position').first()).toHaveText(`1/${yearQuestions.length}`);
  await page.getByRole('button',{name:'Next page'}).click();
  await expect(page.locator('.question-position').first()).toHaveText(`13/${yearQuestions.length}`);
  await page.getByLabel('Filter by subject').selectOption('Anatomy');
  await expect(page.locator('.pyq-filter-metrics')).toContainText(`0/${anatomyQuestions.length}`);
  await expect(page.locator('.question-position').first()).toHaveText(`1/${anatomyQuestions.length}`);
  const question=anatomyQuestions[0];
  await page.locator(`#entry-${question.id}`).click();
  await page.locator(`.option:has(input[value="${question.correct}"])`).click();
  await page.getByRole('button',{name:'Confirm answer'}).click();
  await page.getByRole('button',{name:'Back to papers'}).click();
  await expect(page.locator('.pyq-filter-metrics')).toContainText(`1/${anatomyQuestions.length}`);
  await expect(page.locator('.pyq-filter-metrics')).toContainText('100%');
  await page.getByRole('button',{name:'Clear subject data'}).click();
  await expect(page.getByRole('dialog')).toContainText('Anatomy in 2020');
  await page.getByRole('button',{name:'Cancel'}).click();
  await expect(page.locator('.pyq-filter-metrics')).toContainText(`1/${anatomyQuestions.length}`);
  await page.getByRole('button',{name:'Clear subject data'}).click();
  await page.getByRole('button',{name:'Clear performance'}).click();
  await expect(page.locator('.pyq-filter-metrics')).toContainText(`0/${anatomyQuestions.length}`);
  await expect(page.locator('.pyq-filter-metrics')).toContainText('Accuracy');
  await page.getByRole('button',{name:'Your progress',exact:true}).click();
  await expect(page.getByRole('row',{name:/2020 0\/184/})).toBeVisible();
  await expect(page.locator('.section-panel').first()).toContainText('Total attempted');
});
